-- See https://wiki.hypr.land/configuring/core/autostart/

-- The polkit agent and the desktop portal are started by systemd with
-- graphical-session.target
hl.on("hyprland.start", function ()
    hl.exec_cmd("waybar")
    hl.exec_cmd("nwg-dock-hyprland -d") -- auto-hide, shows when the pointer hits the bottom edge
    hl.exec_cmd("wl-paste --type text --watch cliphist store")  -- Stores only text data
    hl.exec_cmd("wl-paste --type image --watch cliphist store") -- Stores only image data

    -- Show the welcome screen on the first login only
    hl.exec_cmd([[m="${XDG_STATE_HOME:-$HOME/.local/state}/hyprland-welcome-shown"; [ -e "$m" ] || { mkdir -p "${m%/*}" && touch "$m" && exec hyprland-welcome; }]])
end)


