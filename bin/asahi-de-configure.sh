    move  = "20 monitor_h-120",
    float = true,
})
EOF

        # The waybar config shipped in /etc/xdg uses sway modules, so give it
        # Hyprland ones. The default style.css is still picked up from /etc/xdg.
        mkdir -p "$USER_HOME/.config/waybar"
        cat >"$USER_HOME/.config/waybar/config.jsonc" <<'EOF'
{
    "layer": "top",
    "position": "top",
    "height": 30,
    "modules-left": ["hyprland/workspaces"],
    "modules-center": ["hyprland/window"],
    "modules-right": ["tray", "pulseaudio", "network", "battery", "clock"],
    "tray": {
        "spacing": 10
    },
    "pulseaudio": {
        "format": "vol {volume}%",
        "format-muted": "muted",
        "on-click": "wpctl set-mute @DEFAULT_AUDIO_SINK@ toggle"
    },
    "network": {
        "format-wifi": "{essid} {signalStrength}%",
        "format-ethernet": "{ipaddr}",
        "format-disconnected": "offline",
        "tooltip-format": "{ifname} {ipaddr}/{cidr}"
    },
    "battery": {
        "states": {
            "warning": 30,
            "critical": 15
        },
        "format": "bat {capacity}%",
        "format-charging": "chg {capacity}%"
    },
    "clock": {
        "format": "{:%a %d %b %H:%M}",
        "tooltip-format": "<tt>{calendar}</tt>"
    }
}
EOF
        # Fix ownership
        # mkdir -p above may have created ~/.config itself as root
        chown "$USER_NAME:$USER_NAME" "$USER_HOME/.config"
        chown -R "$USER_NAME:$USER_NAME" "$USER_HOME/.config/hypr" "$USER_HOME/.config/waybar"
    else
        echo "Warning: Could not find user home directory for Hyprland config"
    fi
fi

# Clean up the temporary files
rm -f /tmp/calamares-dm /tmp/calamares-de /tmp/calamares-user /tmp/calamares-packages

# Remove cage (no longer needed after setup)
echo "Cleaning up unneeded packages..."
pacman -Rs --noconfirm cage 2>/dev/null || true

# Remove any orphaned dependencies
pacman -Qdtq | xargs -ro pacman -Rns --noconfirm 2>/dev/null || true

echo "DE configuration complete"
