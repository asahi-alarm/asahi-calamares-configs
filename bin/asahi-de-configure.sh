# Post-installation DE configuration
# Enables the appropriate display manager and cleans up minimal image packages

# Disable the first-time setup service
systemctl disable calamares-cage.service

# Lock the root account
usermod -p '*' root

# Read the display manager selection from the de-packages module
DM=$(cat /tmp/calamares-dm 2>/dev/null || echo "sddm")

echo "Configuring display manager: $DM"

case "$DM" in
"plasma-login-manager")
    systemctl enable plasmalogin.service
    ;;
"sddm")
    systemctl enable sddm.service
    ;;
"gdm")
    systemctl enable gdm.service
    ;;
"lightdm")
    systemctl enable lightdm.service
    ;;
"cosmic-greeter")
    systemctl enable cosmic-greeter.service
    ;;
*)
    echo "Unknown display manager: $DM, defaulting to sddm"
    systemctl enable sddm.service
    ;;
esac

# Read the desktop environment selection
DE=$(cat /tmp/calamares-de 2>/dev/null || echo "")

# Read the username from calamares. The de-packages page comes before the
# users page, so the file is usually empty; the users module has created the
# account by now, so fall back to the first regular user.
USER_NAME=$(cat /tmp/calamares-user 2>/dev/null || echo "")
if [ -z "$USER_NAME" ]; then
    USER_NAME=$(getent passwd | awk -F: '$3 >= 1000 && $3 < 60000 { print $1; exit }')
fi
USER_HOME=$(getent passwd "$USER_NAME" | cut -d: -f6)

# Configure DE-specific settings
if [ "$DE" = "hyprland" ]; then
    echo "Configuring Hyprland..."

    # Started with graphical-session.target, which Hyprland and uwsm both
    # bring up once WAYLAND_DISPLAY is in the systemd user environment
    systemctl --global enable hyprpolkitagent.service
    # The portal is normally only D-Bus activated and has no [Install]
    # section, so hook it into the session target explicitly
    systemctl --global add-wants graphical-session.target xdg-desktop-portal-hyprland.service

    if [ -n "$USER_NAME" ] && [ -d "$USER_HOME" ]; then
        echo "Installing Hyprland config for user $USER_NAME at $USER_HOME"
        mkdir -p "$USER_HOME/.config/hypr"
        # Hyprland 0.57+ only reads the Lua config and ignores hyprland.conf
        cat >"$USER_HOME/.config/hypr/hyprland.lua" <<'EOF'
-- Asahi Linux Hyprland configuration, based on the Hyprland 0.57 example config.
-- Refer to the wiki for more information.
-- https://wiki.hypr.land/configuring/

-- Please note not all available settings / options are set here.
-- For a full list, see the wiki

-- You can (and should!!) split this configuration into multiple files
-- Create your files separately and then require them like this:
-- require("myColors")


------------------
---- MONITORS ----
------------------

-- See https://wiki.hypr.land/configuring/core/monitors/
hl.monitor({
    output   = "",
    mode     = "preferred",
    position = "auto",
    scale    = "auto",
})


---------------------
---- MY PROGRAMS ----
---------------------

-- Set programs that you use
local terminal    = "kitty"
local fileManager = "dolphin"
local menu        = "hyprlauncher"


